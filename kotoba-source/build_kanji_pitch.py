"""Bundle exact word/reading pitch matches for the kanji notebook, without changing lessons."""
import argparse
import gzip
import hashlib
import json
import unicodedata
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / 'dist/kanji-pitch-data.mjs'


def kana(text):
    return ''.join(chr(ord(c) - 96) if 'ァ' <= c <= 'ヶ' else c
                   for c in unicodedata.normalize('NFKC', text))


def build(course):
    manifest = json.loads((ROOT / 'dist/dictionary/manifest.json').read_text())
    pack = next(p for p in manifest['packs'] if p['id'] == 'pitch')
    raw = (ROOT / 'dist/dictionary' / pack['file']).read_bytes()
    assert len(raw) == pack['bytes'] and hashlib.sha256(raw).hexdigest() == pack['sha256']
    source = json.loads(gzip.decompress(raw))
    assert source['date'] == pack['date'] and len(source['entries']) == pack['entries']
    targets = {(x[0], kana(x[1])) for k in course['kanji'] for x in k['examples']}
    targets.update((k['practice']['word'], kana(k['practice']['reading'])) for k in course['kanji'])
    candidates = defaultdict(lambda: defaultdict(list))
    for entry in source['entries']:
        for record in entry['a']:
            key = (record['w'], kana(record['r']))
            if key in targets:
                candidates[key][entry['id']].append(record)
    entries = {}
    for word, reading in sorted(targets):
        matches = candidates[(word, reading)]
        # Never borrow from a different spelling/reading or resolve an ambiguous entry.
        entry_id, records = next(iter(matches.items())) if len(matches) == 1 else (None, [])
        patterns = []
        for record in records:
            for pattern in record.get('p', []):
                if pattern not in patterns:
                    patterns.append(pattern)
        entries[json.dumps([word, reading], ensure_ascii=False, separators=(',', ':'))] = {
            'id': entry_id, 'patterns': patterns, 'records': records,
        }
    data = {'sourcePack': {'file': pack['file'], 'date': pack['date'], 'sha256': pack['sha256'],
                           'license': pack['license'], 'sources': pack['sources']},
            'entries': entries}
    return '// Generated by build_kanji_pitch.py; see dictionary/LICENSE.txt.\nexport const KANJI_PITCH = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'


def write_kanji_pitch(course):
    OUTPUT.write_text(build(course))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = build(json.loads((ROOT / 'dist/lesson.json').read_text()))
    if args.check:
        assert OUTPUT.read_text() == result, 'Regenerate notebook pitch data with build_kanji_pitch.py'
        print('PASS notebook pitch bundle matches current course and verified dictionary snapshot')
    else:
        OUTPUT.write_text(result)
        print(f'Wrote {OUTPUT.name}: {len(result.encode())} bytes')
